-- ---------- Configuration ----------
CREATE TABLE IF NOT EXISTS app_settings (
  setting_key    VARCHAR2(50)  CONSTRAINT app_settings_pk PRIMARY KEY,
  setting_value  VARCHAR2(200) NOT NULL,
  description    VARCHAR2(400)
);

CREATE TABLE IF NOT EXISTS app_users (
  user_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  CONSTRAINT app_users_pk PRIMARY KEY,
  username        VARCHAR2(50)  NOT NULL CONSTRAINT app_users_username_uk UNIQUE,
  full_name       VARCHAR2(100) NOT NULL,
  email           VARCHAR2(200),
  role_code       VARCHAR2(20)  NOT NULL
                  CONSTRAINT app_users_role_ck
                  CHECK (role_code IN ('CLERK','APPROVER','FIN_MANAGER','CFO','AUDITOR','ADMIN')),
  approval_limit  NUMBER(14,2) DEFAULT 0 NOT NULL
                  CONSTRAINT app_users_limit_ck CHECK (approval_limit >= 0),
  active_yn       VARCHAR2(1) DEFAULT 'Y' NOT NULL
                  CONSTRAINT app_users_active_ck CHECK (active_yn IN ('Y','N')),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS cost_centers (
  cost_center_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  CONSTRAINT cost_centers_pk PRIMARY KEY,
  cc_code         VARCHAR2(20)  NOT NULL CONSTRAINT cost_centers_code_uk UNIQUE,
  cc_name         VARCHAR2(100) NOT NULL,
  manager_id      NUMBER CONSTRAINT cost_centers_mgr_fk REFERENCES app_users (user_id),
  active_yn       VARCHAR2(1) DEFAULT 'Y' NOT NULL
                  CONSTRAINT cost_centers_active_ck CHECK (active_yn IN ('Y','N'))
);

-- ---------- Master data ----------
CREATE TABLE IF NOT EXISTS vendors (
  vendor_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                      CONSTRAINT vendors_pk PRIMARY KEY,
  vendor_code         VARCHAR2(20)  NOT NULL CONSTRAINT vendors_code_uk UNIQUE,
  vendor_name         VARCHAR2(200) NOT NULL,
  tax_id              VARCHAR2(30)  NOT NULL CONSTRAINT vendors_tax_uk UNIQUE,
  country_code        VARCHAR2(2)   NOT NULL,
  currency_code       VARCHAR2(3)   DEFAULT 'EUR' NOT NULL,
  payment_terms_days  NUMBER(3) DEFAULT 30 NOT NULL
                      CONSTRAINT vendors_terms_ck CHECK (payment_terms_days BETWEEN 0 AND 180),
  status              VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL
                      CONSTRAINT vendors_status_ck CHECK (status IN ('ACTIVE','ON_HOLD','INACTIVE')),
  hold_reason         VARCHAR2(400),
  created_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at          TIMESTAMP,
  CONSTRAINT vendors_hold_reason_ck
    CHECK (status <> 'ON_HOLD' OR hold_reason IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS purchase_orders (
  po_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  CONSTRAINT purchase_orders_pk PRIMARY KEY,
  po_number       VARCHAR2(30) NOT NULL CONSTRAINT purchase_orders_num_uk UNIQUE,
  vendor_id       NUMBER NOT NULL CONSTRAINT purchase_orders_vendor_fk REFERENCES vendors (vendor_id),
  cost_center_id  NUMBER NOT NULL CONSTRAINT purchase_orders_cc_fk REFERENCES cost_centers (cost_center_id),
  order_date      DATE NOT NULL,
  currency_code   VARCHAR2(3) NOT NULL,
  po_amount       NUMBER(14,2) NOT NULL CONSTRAINT purchase_orders_amt_ck CHECK (po_amount > 0),
  status          VARCHAR2(10) DEFAULT 'OPEN' NOT NULL
                  CONSTRAINT purchase_orders_status_ck CHECK (status IN ('OPEN','CLOSED','CANCELLED'))
);

-- ---------- Transactions ----------
CREATE TABLE IF NOT EXISTS invoices (
  invoice_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  CONSTRAINT invoices_pk PRIMARY KEY,
  vendor_id       NUMBER NOT NULL CONSTRAINT invoices_vendor_fk REFERENCES vendors (vendor_id),
  po_id           NUMBER CONSTRAINT invoices_po_fk REFERENCES purchase_orders (po_id),
  cost_center_id  NUMBER NOT NULL CONSTRAINT invoices_cc_fk REFERENCES cost_centers (cost_center_id),
  invoice_number  VARCHAR2(50) NOT NULL,
  invoice_date    DATE NOT NULL,
  received_date   DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
  due_date        DATE NOT NULL,
  currency_code   VARCHAR2(3) NOT NULL,
  net_amount      NUMBER(14,2) NOT NULL CONSTRAINT invoices_net_ck CHECK (net_amount > 0),
  tax_amount      NUMBER(14,2) DEFAULT 0 NOT NULL CONSTRAINT invoices_tax_ck CHECK (tax_amount >= 0),
  gross_amount    NUMBER(14,2) GENERATED ALWAYS AS (net_amount + tax_amount) VIRTUAL,
  status          VARCHAR2(20) DEFAULT 'RECEIVED' NOT NULL
                  CONSTRAINT invoices_status_ck
                  CHECK (status IN ('RECEIVED','FLAGGED','PENDING_APPROVAL','APPROVED','REJECTED','PAID')),
  description     VARCHAR2(400),
  created_by      VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at      TIMESTAMP,
  CONSTRAINT invoices_vendor_inv_uk UNIQUE (vendor_id, invoice_number),
  CONSTRAINT invoices_dates_ck CHECK (due_date >= invoice_date)
);

-- ---------- Approval workflow ----------
CREATE TABLE IF NOT EXISTS approval_rules (
  rule_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  CONSTRAINT approval_rules_pk PRIMARY KEY,
  approval_level  NUMBER(1) NOT NULL,
  min_amount      NUMBER(14,2) NOT NULL,
  max_amount      NUMBER(14,2),
  approver_role   VARCHAR2(20) NOT NULL
                  CONSTRAINT approval_rules_role_ck
                  CHECK (approver_role IN ('APPROVER','FIN_MANAGER','CFO')),
  CONSTRAINT approval_rules_range_ck CHECK (max_amount IS NULL OR max_amount > min_amount),
  CONSTRAINT approval_rules_level_uk UNIQUE (approval_level)
);

CREATE TABLE IF NOT EXISTS invoice_approvals (
  approval_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  CONSTRAINT invoice_approvals_pk PRIMARY KEY,
  invoice_id      NUMBER NOT NULL
                  CONSTRAINT invoice_approvals_inv_fk REFERENCES invoices (invoice_id) ON DELETE CASCADE,
  approval_level  NUMBER(1) NOT NULL,
  approver_id     NUMBER CONSTRAINT invoice_approvals_user_fk REFERENCES app_users (user_id),
  decision        VARCHAR2(10) DEFAULT 'PENDING' NOT NULL
                  CONSTRAINT invoice_approvals_dec_ck CHECK (decision IN ('PENDING','APPROVED','REJECTED')),
  decision_at     TIMESTAMP,
  comments        VARCHAR2(1000),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT invoice_approvals_uk UNIQUE (invoice_id, approval_level),
  CONSTRAINT invoice_approvals_decat_ck CHECK (decision = 'PENDING' OR decision_at IS NOT NULL)
);

-- ---------- Anomaly detection ----------
CREATE TABLE IF NOT EXISTS anomaly_types (
  anomaly_code  VARCHAR2(30) CONSTRAINT anomaly_types_pk PRIMARY KEY,
  description   VARCHAR2(400) NOT NULL,
  severity      VARCHAR2(10) NOT NULL
                CONSTRAINT anomaly_types_sev_ck CHECK (severity IN ('LOW','MEDIUM','HIGH')),
  active_yn     VARCHAR2(1) DEFAULT 'Y' NOT NULL
                CONSTRAINT anomaly_types_active_ck CHECK (active_yn IN ('Y','N'))
);

CREATE TABLE IF NOT EXISTS invoice_anomalies (
  anomaly_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                   CONSTRAINT invoice_anomalies_pk PRIMARY KEY,
  invoice_id       NUMBER NOT NULL
                   CONSTRAINT invoice_anomalies_inv_fk REFERENCES invoices (invoice_id) ON DELETE CASCADE,
  anomaly_code     VARCHAR2(30) NOT NULL
                   CONSTRAINT invoice_anomalies_type_fk REFERENCES anomaly_types (anomaly_code),
  details          VARCHAR2(1000),
  status           VARCHAR2(10) DEFAULT 'OPEN' NOT NULL
                   CONSTRAINT invoice_anomalies_status_ck CHECK (status IN ('OPEN','RESOLVED','DISMISSED')),
  detected_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  resolved_by      VARCHAR2(100),
  resolved_at      TIMESTAMP,
  resolution_note  VARCHAR2(1000),
  CONSTRAINT invoice_anomalies_uk UNIQUE (invoice_id, anomaly_code)
);

-- ---------- Audit (no FKs on purpose: log rows must outlive deleted data) ----------
CREATE TABLE IF NOT EXISTS audit_log (
  log_id       NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT audit_log_pk PRIMARY KEY,
  table_name   VARCHAR2(30) NOT NULL,
  record_id    NUMBER,
  action       VARCHAR2(20) NOT NULL
               CONSTRAINT audit_log_action_ck
               CHECK (action IN ('INSERT','UPDATE','DELETE','STATUS_CHANGE','JOB_RUN','ERROR')),
  old_values   JSON,
  new_values   JSON,
  message      VARCHAR2(4000),
  changed_by   VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
  changed_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ---------- Indexes on foreign keys and common filters ----------
CREATE INDEX IF NOT EXISTS invoices_po_ix          ON invoices (po_id);
CREATE INDEX IF NOT EXISTS invoices_cc_ix          ON invoices (cost_center_id);
CREATE INDEX IF NOT EXISTS invoices_status_ix      ON invoices (status);
CREATE INDEX IF NOT EXISTS invoices_dup_ix         ON invoices (vendor_id, gross_amount, invoice_date);
CREATE INDEX IF NOT EXISTS purchase_orders_vend_ix ON purchase_orders (vendor_id);
CREATE INDEX IF NOT EXISTS purchase_orders_cc_ix   ON purchase_orders (cost_center_id);
CREATE INDEX IF NOT EXISTS cost_centers_mgr_ix     ON cost_centers (manager_id);
CREATE INDEX IF NOT EXISTS invoice_approvals_usr_ix ON invoice_approvals (approver_id);
CREATE INDEX IF NOT EXISTS invoice_anomalies_typ_ix ON invoice_anomalies (anomaly_code);
CREATE INDEX IF NOT EXISTS audit_log_record_ix     ON audit_log (table_name, record_id);